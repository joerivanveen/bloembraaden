<?php

declare(strict_types = 1);

namespace Bloembraaden;

class File extends BaseElement
{
    /**
     * Content types that cannot execute scripts and may be shown in the browser, all others are sent as attachment
     * (besides these, audio/* and video/* are also shown inline)
     */
    private const INLINE_CONTENT_TYPES = array(
        'application/pdf',
        'image/png',
        'image/jpeg',
        'image/gif',
        'image/webp',
        'text/plain',
    );

    public function __construct(?\stdClass $row = null)
    {
        parent::__construct($row);
        $this->type_name = 'file';
    }

    public function create(?bool $online = true): ?int
    {
        return db()->insertElement($this->getType(), array(
            'title' => __('New file', 'peatcms'),
            'content_type' => 'application/octet-stream',
            'filename_saved' => '',
            'slug' => 'file',
            'online' => $online,
        ));
    }

    /**
     * Serves the file if possible, else throws a fatal error
     * In any case execution is halted
     */
    public function serve(): void
    {
        // make sure nothing has been sent
        if (headers_sent()) {
            $this->handleErrorAndStop("Headers already sent, cannot serve file {$this->row->slug}.", __('Error serving file.', 'peatcms'));
        } else {
            $filename_saved = (string)$this->row->filename_saved;
            // the saved filename is generated by Bloembraaden and must never point outside the uploads folder
            if ('' === $filename_saved || $filename_saved !== basename($filename_saved) || str_contains($filename_saved, '..')) {
                $this->handleErrorAndStop("Invalid filename_saved for file {$this->row->slug}.", __('File not found on server.', 'peatcms'));
            }
            $filename = Setup::$UPLOADS . $filename_saved; // 'uploads' is base folder of XSendFile extension
            if (file_exists($filename)) {
                $content_type = strtolower(trim((string)$this->row->content_type));
                // only types that cannot run scripts may be shown in the browser, everything else must be downloaded
                $inline = in_array($content_type, self::INLINE_CONTENT_TYPES, true)
                    || str_starts_with($content_type, 'audio/')
                    || str_starts_with($content_type, 'video/');
                $download_name = $this->row->slug;
                if ('' !== ($extension = (string)($this->row->extension ?? ''))) $download_name .= ".$extension";
                $ascii_name = preg_replace('/[^A-Za-z0-9._-]/', '_', $download_name);
                header(sprintf('Content-Disposition: %s; filename="%s"; filename*=UTF-8\'\'%s',
                    $inline ? 'inline' : 'attachment', $ascii_name, rawurlencode($download_name)));
                header('Content-Type: ' . ('' === $content_type ? 'application/octet-stream' : $content_type));
                // https://dev.to/gbhorwood/nginx-serving-private-files-with-x-accel-redirect-57dl
                header("X-Accel-Redirect: /private_uploads/$filename_saved");
                die();
            } else {
                $this->handleErrorAndStop("$filename not found", __('File not found on server.', 'peatcms'));
            }
        }
    }
}

